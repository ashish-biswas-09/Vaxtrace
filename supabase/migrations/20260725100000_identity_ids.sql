-- Unique, immutable, system-generated identifiers for every actor in the system.
--
--   Child            -> children.child_id       10 digits, e.g. "1000000185"
--   Worker / Admin   -> user_roles.staff_code   "WKR-000004" / "ADM-000001"
--
-- Why the database and not app code: these IDs are the primary identification number used
-- for reporting, tracking and auditing. If any write path can supply or change one, the
-- guarantee is worthless. Generation happens in a BEFORE INSERT trigger (client input is
-- overwritten, not merely defaulted) and mutation is rejected in BEFORE UPDATE — so the
-- invariant holds for server actions, SQL console, service-role jobs and future importers
-- alike. Uniqueness is by construction (sequence), not by retry-on-collision.

-- ---------------------------------------------------------------------------
-- Luhn check digit (ISO/IEC 7812). The 10th digit is a checksum over the first 9,
-- so a mistyped or transposed Child ID is rejected at data entry instead of silently
-- attaching a dose to the wrong child. This is why the ID is 10 digits, not 9.
-- ---------------------------------------------------------------------------
create or replace function public.luhn_check_digit(p_digits text)
returns int language plpgsql immutable strict set search_path = public as $$
declare
  s   int := 0;
  d   int;
  i   int;
  dbl boolean := true;   -- rightmost digit of p_digits is doubled (check digit is appended after it)
begin
  if p_digits !~ '^[0-9]+$' then
    raise exception 'luhn_check_digit: non-numeric input';
  end if;
  for i in reverse length(p_digits)..1 loop
    d := substr(p_digits, i, 1)::int;
    if dbl then
      d := d * 2;
      if d > 9 then d := d - 9; end if;
    end if;
    s   := s + d;
    dbl := not dbl;
  end loop;
  return (10 - (s % 10)) % 10;
end $$;

-- ---------------------------------------------------------------------------
-- CHILD ID
-- ---------------------------------------------------------------------------
-- Starts at 100000000 so the payload is always exactly 9 digits (no leading-zero
-- ambiguity when the ID is stored, printed on a card, or read over the phone).
create sequence public.child_id_seq start with 100000000 maxvalue 999999999 no cycle;

create or replace function public.next_child_id()
returns text language plpgsql volatile set search_path = public as $$
declare v_body text;
begin
  v_body := nextval('public.child_id_seq')::text;
  return v_body || luhn_check_digit(v_body)::text;
end $$;

alter table children add column child_id text;

-- Backfill existing rows before the NOT NULL / UNIQUE constraints land.
update children set child_id = next_child_id() where child_id is null;

alter table children
  alter column child_id set not null,
  add constraint children_child_id_key unique (child_id),
  add constraint children_child_id_format check (child_id ~ '^[0-9]{10}$');

create or replace function public.trg_child_id_guard() returns trigger
language plpgsql set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    new.child_id := next_child_id();   -- always server-generated; any client value is discarded
  elsif new.child_id is distinct from old.child_id then
    raise exception 'child_id is immutable (child %)', old.id
      using errcode = 'restrict_violation';
  end if;
  return new;
end $$;

create trigger child_id_guard before insert or update on children
  for each row execute function public.trg_child_id_guard();

-- The DEFAULT exists only so callers (and the generated TypeScript Insert type) can omit
-- the column; the guard above overwrites it. Cost is one spare sequence value per insert,
-- and sequences are not gapless by contract.
alter table children alter column child_id set default public.next_child_id();

comment on column children.child_id is
  'Immutable 10-digit Child ID: 9 sequence digits + Luhn check digit. Generated by child_id_guard.';

-- ---------------------------------------------------------------------------
-- WORKER / ADMIN ID
-- ---------------------------------------------------------------------------
-- Keyed on user_roles, not profiles: the identifier names a *capacity*, so a person who
-- is both a worker and an admin holds one of each, and neither number is reused. Per-role
-- sequences keep the human-readable counter meaningful ("worker #7").
create sequence public.staff_code_admin_seq  start with 1;
create sequence public.staff_code_worker_seq start with 1;
create sequence public.staff_code_parent_seq start with 1;

create or replace function public.next_staff_code(p_role user_role)
returns text language plpgsql volatile set search_path = public as $$
begin
  -- IF, not SQL CASE: only the taken branch may consume a sequence value.
  if p_role = 'admin' then
    return 'ADM-' || lpad(nextval('public.staff_code_admin_seq')::text, 6, '0');
  elsif p_role = 'worker' then
    return 'WKR-' || lpad(nextval('public.staff_code_worker_seq')::text, 6, '0');
  else
    return 'PAR-' || lpad(nextval('public.staff_code_parent_seq')::text, 6, '0');
  end if;
end $$;

alter table user_roles add column staff_code text;

update user_roles set staff_code = next_staff_code(role) where staff_code is null;

alter table user_roles
  alter column staff_code set not null,
  add constraint user_roles_staff_code_key unique (staff_code),
  add constraint user_roles_staff_code_format check (staff_code ~ '^(ADM|WKR|PAR)-[0-9]{6}$');

create or replace function public.trg_staff_code_guard() returns trigger
language plpgsql set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    new.staff_code := next_staff_code(new.role);
  elsif new.staff_code is distinct from old.staff_code then
    raise exception 'staff_code is immutable (user %)', old.user_id
      using errcode = 'restrict_violation';
  end if;
  return new;
end $$;

create trigger staff_code_guard before insert or update on user_roles
  for each row execute function public.trg_staff_code_guard();

-- A column default cannot see NEW.role, so it cannot call next_staff_code(). This sentinel
-- exists only to make the column optional to callers; it deliberately VIOLATES the format
-- check above, so if the guard is ever bypassed the insert fails instead of storing junk.
alter table user_roles alter column staff_code set default 'UNSET';

comment on column user_roles.staff_code is
  'Immutable per-role identifier (ADM-/WKR-/PAR-nnnnnn). Generated by staff_code_guard.';

-- Trigger functions fire as the table owner; no client role needs EXECUTE on them
-- (same rule as 20260724115300_harden.sql).
revoke execute on function public.trg_child_id_guard()   from anon, authenticated, public;
revoke execute on function public.trg_staff_code_guard() from anon, authenticated, public;
revoke execute on function public.next_child_id()        from anon, authenticated, public;
revoke execute on function public.next_staff_code(user_role) from anon, authenticated, public;

-- The Custom Access Token Hook selects from user_roles as supabase_auth_admin; it now
-- reads a wider row, and column privileges are per-column on that grant.
grant select on public.user_roles to supabase_auth_admin;
